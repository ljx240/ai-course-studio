import type { Parameters } from '../../../packages/subject-sdk'

type Trial = [label: string, parameters: Parameters]

interface Activity {
  gesture: string
  question: string
  choices: readonly [string, string, string]
  correct: number
  trials: readonly [Trial, Trial]
  readouts: string[]
  explanation: string
}

function activity(gesture: string, question: string, choices: Activity['choices'], correct: number,
  a: Trial, b: Trial, readouts: string[], explanation: string): Activity {
  return { gesture, question, choices, correct, trials: [a, b], readouts, explanation }
}

