async def setup_model(browser):
    page = await browser.new_page(viewport={"width": 1600, "height": 980}, device_scale_factor=1)
    await page.goto(MODEL_URL)
    await expect(page.get_by_role("button", name="配置模型", exact=True)).to_be_visible()
    settings_path = MODEL_URL.removesuffix("studio/") + "api/settings/ai-provider"
    malformed = await page.request.post(settings_path, data={"api_key": "redaction-check"})
    assert malformed.status == 422 and "redaction-check" not in await malformed.text()
    cross_origin = await page.request.get(settings_path, headers={"Origin": "https://example.com"})
    assert cross_origin.status == 403
    await page.get_by_role("button", name="AI 服务设置").click()
    settings = page.get_by_role("dialog", name="AI 服务设置")
    await settings.get_by_label("服务地址").fill(MODEL_FIXTURE_URL)
    await settings.get_by_label("模型 ID").fill("protocol-fixture")
    key = settings.get_by_label("API 密钥", exact=True)
    await key.fill("rejected-fixture-key")
    await settings.get_by_role("button", name="测试连接").click()
    await expect(settings.get_by_role("alert")).to_contain_text("HTTP 401")
    await key.fill("local-fixture")
    await settings.get_by_role("button", name="测试连接").click()
    await expect(settings.get_by_role("status")).to_contain_text("连接成功")
    assert not (await (await page.request.get(settings_path)).json())["configured"]
    await settings.get_by_role("button", name="保存配置").click()
    await expect(settings.get_by_role("status")).to_contain_text("配置已保存")
    await settings.get_by_role("button", name="关闭").click()
    await page.reload()
    await page.get_by_role("button", name="AI 服务设置").click()
    await expect(settings.get_by_label("服务地址")).to_have_value(MODEL_FIXTURE_URL)
    await expect(settings.get_by_label("模型 ID")).to_have_value("protocol-fixture")
    await expect(key).to_have_value("")
    await settings.get_by_role("button", name="关闭").click()
    await expect(page.get_by_text("模型已配置", exact=True)).to_be_visible()
    return page


async def tutor_questions(page):
    question = page.get_by_role("textbox", name="向 AI 学伴提问")
    log = page.get_by_role("log", name="学伴对话")
    tabs = page.get_by_role("tablist", name="学习面板")
