async def classroom(browser, url, model=False, revised=False):
    page = await browser.new_page(viewport={"width": 1440, "height": 900})
    await page.add_init_script("""Object.defineProperty(window, 'speechSynthesis', {
      value: {getVoices: () => [{localService: true, lang: 'zh-CN'}], speak() {this.speaking = true},
        pause() {}, resume() {}, cancel() {this.speaking = false}}
    });
    window.SpeechSynthesisUtterance = class { constructor(text) { this.text = text; } };
    """)
    await page.goto(url)
    await page.get_by_role("button", name="课堂讲解").click()
    await expect(page.get_by_role("heading", name="课堂讲解：平抛运动")).to_be_visible()
