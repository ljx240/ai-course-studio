    await page.get_by_role("button", name="下一步").click()
    await expect(page.locator(".classroom-caption")).to_contain_text(
        "本机协议夹具返回的修订内容。" if revised else "沿水平方向抛出"
    )
    await page.get_by_role("button", name="播放讲解").click()
    await expect(page.get_by_role("button", name="暂停讲解")).to_be_visible()
    if model:
        await page.get_by_role("button", name="解释当前内容").click()
        await expect(page.get_by_role("group", name="模型回答")).to_be_visible()
    else:
        await page.get_by_role("button", name="暂停讲解").click()
