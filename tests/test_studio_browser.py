    await expect(tutor_tab).to_have_attribute("aria-selected", "true")

    # Deliver the first answer while another tab is open.
    resume_reply = asyncio.Event()
    async def hold_reply(route):
        await resume_reply.wait()
        await route.continue_()

    await page.route("**/api/studio/tutor", hold_reply, times=1)
    await page.get_by_role("button", name="总结本节").click()
    await expect(log.get_by_role("status")).to_contain_text("正在生成回答")
